#!/usr/bin/env python3
"""R15 UI family: regenerate ui_accessors.generated.h from the committed
slot map (ui_slots.generated.h) and the current accessor file's cast map.

The accessor header maps every canonical UI symbol to UI_Get() on
NATIVE_LINUX and adds a <Symbol>_SIZE literal (expected decoded payload
size) so runtime code that needs the payload size (Alloc / CpuCopy /
LoadPalette byte counts) does not fall into the sizeof(pointer) trap
when the symbol is a macro.

Usage:
  gen_ui_accessors.py [--check]

--check regenerates to a temp file and requires the committed header to
be byte-identical.
"""
import re
import sys

ROOT = "/home/tristen/work/pokeemerald-recomp"
SLOTS = f"{ROOT}/include/emerald/resources/ui_slots.generated.h"
ACCESSORS = f"{ROOT}/include/emerald/resources/ui_accessors.generated.h"

# Cross-family slots: owned by the tileset family's native seam
# (TILESET_NATIVE_ARRAY); the UI accessor must not macro them or the
# tileset native header breaks in TUs that see both.
CROSS_FAMILY_SEAM = {
    "gTilesetAnims_BattleDomePals0_0",
    "gTilesetAnims_BattleDomePals0_1",
    "gTilesetAnims_BattleDomePals0_2",
    "gTilesetAnims_BattleDomePals0_3",
    "gTilesetTiles_General",
}

HEADER = """/* Generated by R15 UI family generator
 * Do not edit by hand.
 *
 * R15: on native every legacy UI symbol name redirects
 * to the compat seam accessor; on GBA the names stay the real INCBIN
 * arrays. Each symbol also carries a <Symbol>_SIZE literal (expected
 * decoded payload size from the slot map) for runtime code that needs
 * the byte size of the payload. */
#if defined(NATIVE_LINUX)
#include "emerald/resources/emerald_ui_compat.h"
"""


def parse_slots():
    """Return {id_lower: expected_size} from the committed slot map."""
    text = open(SLOTS).read()
    out = {}
    for m in re.finditer(
        r'\{\s*"([^"]+)"\s*,\s*(\d+)u?\s*,', text):
        out[m.group(1)] = int(m.group(2))
    return out


def parse_accessors():
    """Return ordered [(symbol, cast, id)] from the committed accessors."""
    text = open(ACCESSORS).read()
    out = []
    for m in re.finditer(
        r'#define (\w+) \(\(const (\w+) \*\)UI_Get\("([^"]+)"\)\)', text):
        out.append((m.group(1), m.group(2), m.group(3)))
    return out


def source_element_types():
    """The GBA array element type per symbol, from the checked-in C
    definitions (ground truth for pointer arithmetic and struct-field
    compatibility; the manifest 'type' field alone is not precise enough)."""
    import glob
    elt = {}
    for c in glob.glob(f"{ROOT}/src/**/*.c", recursive=True) + \
            glob.glob(f"{ROOT}/src/**/*.h", recursive=True):
        for m in re.finditer(
            r"^\s*(?:const\s+)?(u8|u16|u32|s8|s16|s32)\s+(\w+)\s*\[\s*\]\s*=",
            open(c).read(), re.M):
            elt[m.group(2)] = m.group(1)
    return elt


def main():
    check = "--check" in sys.argv
    slots = parse_slots()
    accessors = parse_accessors()
    elt = source_element_types()
    lines = [HEADER]
    for symbol, cast, rid in accessors:
        if symbol in CROSS_FAMILY_SEAM:
            continue  # tileset-family-owned; not macro'd on native
        size = slots.get(rid)
        if size is None:
            raise SystemExit(f"no slot for {rid}")
        if symbol in elt:
            cast = elt[symbol]
        lines.append(
            f'#define {symbol} ((const {cast} *)UI_Get("{rid}"))\n')
        lines.append(f"#define {symbol}_SIZE {size}u\n")
    lines.append("#endif\n")
    generated = "".join(lines)
    if check:
        current = open(ACCESSORS).read()
        if current != generated:
            raise SystemExit(
                "ui_accessors.generated.h differs from generator output")
        print("gen_ui_accessors --check: byte-identical")
        return
    open(ACCESSORS, "w").write(generated)
    print(f"regenerated {ACCESSORS}: {len(accessors)} symbols")


if __name__ == "__main__":
    main()
